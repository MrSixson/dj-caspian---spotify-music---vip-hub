-- Register Android/iOS device tokens for DJ Caspian push notifications.
create table if not exists public.device_push_tokens (
  id bigint generated by default as identity primary key,
  installation_id text not null,
  fcm_token text not null unique,
  platform text not null check (platform in ('android', 'ios')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.device_push_tokens enable row level security;

-- A device may register its own token without exposing the token list to clients.
drop policy if exists "devices can register push tokens" on public.device_push_tokens;
create policy "devices can register push tokens"
  on public.device_push_tokens
  for insert
  to anon, authenticated
  with check (
    length(installation_id) between 8 and 100
    and length(fcm_token) between 20 and 4096
  );

-- No public SELECT, UPDATE, or DELETE policy is intentionally created.
